"""IaCSecBench — LaTeX table emission.

Every result table in the manuscript is written from here. No table is
hand-authored, so a number in the paper cannot drift from the measurement that
produced it.

Split out of :mod:`evaluation.analyze`, which retains aggregation, the
statistical comparisons and the CLI. Presentation-only data lives here too:
display labels, the not-estimable marker, and the layer names.

Conventions these emitters hold to
----------------------------------
Numeric columns are ``r``, never ``c``. Each is emitted to a fixed number of
decimal places, which is what makes right alignment line the decimal points up;
centring does not, once a value crosses from one integer digit to two.
``siunitx`` is deliberately not used: the fixed decimal places make it
unnecessary, and its option names differ between versions 2 and 3.

Interval and label columns stay left-aligned or wrap in an ``X`` column. They
are not numbers, and right-aligning them ragged the opening brackets.
"""

from __future__ import annotations

import re
from typing import TYPE_CHECKING, Any

from evaluation.normalize import MatchLevel
from evaluation.stats import ConfusionMatrix

if TYPE_CHECKING:  # pragma: no cover - annotations only
    from evaluation.analyze import ToolResult

TOOL_LABELS = {
    "checkov": ("Checkov", "AST static analysis"),
    "tfsec": ("tfsec", "HCL lexical scanning"),
    "trivy": ("Trivy", "HCL scanning, tfsec successor"),
    "opa": ("OPA (plan-level)", "Rego over compiled plan"),
    "iacsecbench": ("IaCSecBench", "Composite pipeline"),
    "iacsb_layer1": ("IaCSecBench L1", "Repository-edge scanning"),
}

NOT_ESTIMABLE = "n/e"


def _fmt_pct(value: float | None, estimable: bool = True) -> str:
    if not estimable or value is None:
        return NOT_ESTIMABLE
    return f"{value * 100:.2f}"


def _fmt_ci(matrix: ConfusionMatrix, which: str, estimable: bool = True) -> str:
    if not estimable:
        return NOT_ESTIMABLE
    interval = getattr(matrix, f"{which}_ci")().as_pct()
    return f"$[{interval.lower:.2f}, {interval.upper:.2f}]$"


def _fmt_p(value: float) -> str:
    """Formats a p-value for a right-aligned column.

    Always three decimal places, so the column's decimal points align under right
    alignment. ``<0.001`` is one glyph wider than a bare value; right alignment
    still lines the decimals up because the comparator sits to the left of the
    digits rather than displacing them.
    """
    if value < 0.001:
        return "$<0.001$"
    return f"${value:.3f}$"


def emit_performance_table(
    results: dict[str, dict[MatchLevel, ToolResult]],
    status: dict[str, str],
    level: MatchLevel,
    n_cases: int,
    n_positives: int,
    n_negatives: int,
) -> str:
    """Emits the main performance table with exact confidence intervals."""
    lines = [
        "% Generated by evaluation/analyze.py -- do not edit by hand.",
        "% Regenerate with: python -m evaluation.analyze",
        f"% Matching strictness level: {level}",
        "\\begin{table*}[!t]",
        "\\caption{Detection performance on the admissible corpus "
        f"($N = {n_cases}$: {n_positives} vulnerable, {n_negatives} compliant). "
        "Intervals are exact Clopper--Pearson at the 95\\% level. "
        f"Entries marked {NOT_ESTIMABLE} are not estimable from this corpus.}}",
        "\\label{tab:performance}",
        "\\centering",
        "\\small",
        "\\setlength{\\tabcolsep}{4pt}",
        # Counts and percentages are right-aligned so their decimal points line up;
        # each is emitted to a fixed number of decimal places below, which is what
        # makes right alignment sufficient. Interval columns stay left-aligned:
        # they are bracketed literals, not numbers, and right-aligning them would
        # ragged the opening brackets.
        "\\begin{tabular}{l r r r r r l r l r}",
        "\\toprule",
        "\\textbf{Tool} & \\textbf{TP} & \\textbf{FP} & \\textbf{TN} & \\textbf{FN} & "
        "\\textbf{Rec.\\ (\\%)} & \\textbf{Rec.\\ 95\\% CI} & "
        "\\textbf{Prec.\\ (\\%)} & \\textbf{Prec.\\ 95\\% CI} & \\textbf{MCC} \\\\",
        "\\midrule",
    ]

    for tool in sorted(results):
        if status.get(tool) != "run":
            continue
        result = results[tool][level]
        m = result.matrix
        label = TOOL_LABELS.get(tool, (tool, ""))[0]
        mcc = f"{m.mcc:.3f}" if result.mcc_estimable else NOT_ESTIMABLE
        lines.append(
            f"{label} & {m.tp} & {m.fp} & {m.tn} & {m.fn} & "
            f"{_fmt_pct(m.recall)} & {_fmt_ci(m, 'recall')} & "
            f"{_fmt_pct(m.precision)} & {_fmt_ci(m, 'precision')} & {mcc} \\\\"
        )

    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]

    not_run = sorted(t for t, s in status.items() if s == "not_run")
    if not_run:
        labels = ", ".join(TOOL_LABELS.get(t, (t, ""))[0] for t in not_run)
        lines.insert(
            -1,
            f"% Not installed in the measurement environment and therefore excluded: {labels}.",
        )
    return "\n".join(lines)


# Which tools constitute which validation layer of the composed pipeline.
# Layer 2 (native module testing) is absent by design: `terraform test` validates
# module behaviour -- variable constraints, outputs, conditional creation -- and
# is not a misconfiguration detector over single-resource security cases. Claiming
# a layer-2 detection count on this corpus would misrepresent what the layer does.
PIPELINE_LAYERS = {
    "L1 (repository edge)": "iacsb_layer1",
    "L3 (compiled plan)": "opa",
}
LAYER2_NOTE = (
    "Layer 2 (native module testing) is not scored: it validates module behaviour "
    "rather than detecting resource misconfiguration, so it has no detection "
    "count on this corpus."
)


def emit_layer_table(
    results: dict[str, dict[MatchLevel, ToolResult]],
    status: dict[str, str],
    level: MatchLevel,
    n_positives: int,
) -> str:
    """Emits layer attribution with explicit overlap between layers.

    Intersection sizes are reported alongside per-layer counts. A strictly
    additive attribution -- each layer detecting a disjoint case set -- is
    implausible on a real corpus, so the overlap is stated rather than left to be
    inferred from totals that happen to sum.
    """
    detected: dict[str, set[str]] = {}
    for label, tool in PIPELINE_LAYERS.items():
        if status.get(tool) != "run":
            continue
        outcomes = results[tool][level].outcomes
        detected[label] = {cid for cid, cls in outcomes.items() if cls == "TP"}

    lines = [
        "% Generated by evaluation/analyze.py -- do not edit by hand.",
        "\\begin{table}[!t]",
        "\\caption{Layer attribution over the vulnerable cases. Overlap is reported "
        "explicitly: layers are not assumed to detect disjoint sets. " + LAYER2_NOTE + "}",
        "\\label{tab:layers}",
        "\\centering",
        "\\small",
        # The configuration column is an X column so a long label wraps inside the
        # cell instead of pushing the numeric columns off the edge of the float.
        # tabularx needs an explicit target width; \columnwidth is the IEEE
        # two-column measure this table is set in.
        "\\begin{tabularx}{\\columnwidth}{@{}X r r@{}}",
        "\\toprule",
        "\\textbf{Configuration} & \\textbf{Detected} & \\textbf{Recall (\\%)} \\\\",
        "\\midrule",
    ]

    def row(label: str, cases: set[str]) -> str:
        pct = (len(cases) / n_positives * 100.0) if n_positives else 0.0
        return f"{label} & {len(cases)} & {pct:.2f} \\\\"

    for label in sorted(detected):
        lines.append(row(label, detected[label]))

    if len(detected) >= 2:
        labels = sorted(detected)
        lines.append("\\midrule")
        for i, first in enumerate(labels):
            for second in labels[i + 1 :]:
                overlap = detected[first] & detected[second]
                # Spelling both layers out in full ("L1 (repository edge) $\cap$
                # L3 (compiled plan)") overran the column. The parenthetical
                # gloss is already carried by the rows above, so the short
                # identifier is unambiguous here and fits.
                lines.append(
                    f"\\quad {_layer_key(first)} $\\cap$ {_layer_key(second)} "
                    f"(overlap) & {len(overlap)} & "
                    f"{(len(overlap) / n_positives * 100.0) if n_positives else 0.0:.2f} \\\\"
                )
        union: set[str] = set()
        for cases in detected.values():
            union |= cases
        lines.append("\\midrule")
        lines.append(
            f"\\textbf{{Union of scored layers}} & \\textbf{{{len(union)}}} & "
            f"\\textbf{{{(len(union) / n_positives * 100.0) if n_positives else 0.0:.2f}}} \\\\"
        )

    lines += ["\\bottomrule", "\\end{tabularx}", "\\end{table}", ""]
    return "\n".join(lines)


def _layer_key(label: str) -> str:
    """Reduces ``"L1 (repository edge)"`` to ``"L1"`` for use in overlap rows.

    Falls back to the full label when there is no parenthetical to strip, so an
    added layer without the ``Ln (gloss)`` shape still names itself rather than
    silently emitting an empty cell.
    """
    return label.split(" (", 1)[0].strip() or label


def emit_strictness_table(
    results: dict[str, dict[MatchLevel, ToolResult]], status: dict[str, str]
) -> str:
    """Emits recall under each matching strictness level.

    The gap between the ``control`` and ``any`` columns quantifies how much of a
    tool's apparent detection rate comes from findings unrelated to the
    vulnerability the case was authored to contain.
    """
    lines = [
        "% Generated by evaluation/analyze.py -- do not edit by hand.",
        "\\begin{table}[!t]",
        "\\caption{Recall under three finding-matching criteria. "
        "\\emph{Control} credits a detection only when the tool's rule maps to the "
        "control the case violates; \\emph{resource} credits any finding on the "
        "expected resource; \\emph{any} credits any finding whatsoever. The spread "
        "measures attribution precision.}",
        "\\label{tab:strictness}",
        "\\centering",
        "\\small",
        # Right-aligned for the same reason as the performance table: fixed decimal
        # places make right alignment line the decimal points up, and centring does
        # not once a value crosses from one integer digit to two.
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}l r r r@{}}",
        "\\toprule",
        "\\textbf{Tool} & \\textbf{Control (\\%)} & \\textbf{Resource (\\%)} & "
        "\\textbf{Any (\\%)} \\\\",
        "\\midrule",
    ]
    for tool in sorted(results):
        if status.get(tool) != "run":
            continue
        label = TOOL_LABELS.get(tool, (tool, ""))[0]
        cells = " & ".join(
            _fmt_pct(
                results[tool][lvl].matrix.recall,
                estimable=(lvl != "resource" or results[tool][lvl].n_resource_applicable > 0),
            )
            for lvl in ("control", "resource", "any")
        )
        lines.append(f"{label} & {cells} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def emit_latency_table(
    results: dict[str, dict[MatchLevel, ToolResult]], status: dict[str, str], repeats: int
) -> str:
    lines = [
        "% Generated by evaluation/analyze.py -- do not edit by hand.",
        "\\begin{table}[!t]",
        # The plan-level exclusion belongs in the caption, not only in the prose
        # that surrounds it. A table is extracted, pasted into slides and quoted in
        # reviews on its own, and read that way an 18 ms figure next to a 2.4 s one
        # invites a conclusion about relative cost that the measurement does not
        # support.
        f"\\caption{{Measured per-case execution latency over {repeats} repetitions. "
        "Values are mean $\\pm$ standard deviation on the environment recorded in "
        "\\texttt{results/run\\_manifest.json}. Each tool is measured at its own "
        "interface: the plan-level figure covers policy evaluation over an "
        "already-compiled plan document and excludes the \\texttt{terraform init} "
        "and \\texttt{terraform plan} invocations that produce it, which dominate "
        "that layer's wall-clock cost in continuous integration. It is therefore a "
        "lower bound, and is not comparable with the source-level figures, which "
        "have no equivalent preparation step.}",
        "\\label{tab:latency}",
        "\\centering",
        "\\small",
        # Mean and standard deviation are separate right-aligned columns joined by
        # a \pm placed in the inter-column gap, so the \pm signs form a vertical
        # line and each side's decimal points align independently. Emitted as one
        # right-flushed string ("$2371.0 \pm 85.8$") only the final glyph aligned:
        # 2371.0 and 0.2 sat with their decimal points three places apart and the
        # \pm signs wandered with them.
        # tabularx, not tabular: as a fixed-width tabular this table ran 29pt past
        # the column edge, because the paradigm labels are long and the widest mean
        # is four digits. An X column absorbs the slack by wrapping the label rather
        # than pushing the numbers out of the float.
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabularx}{\\columnwidth}{@{}l X r@{\\,$\\pm$\\,}r@{}}",
        "\\toprule",
        "\\textbf{Tool} & \\textbf{Evaluation layer} & "
        "\\multicolumn{2}{c}{\\textbf{Latency (ms)}} \\\\",
        "\\midrule",
    ]
    for tool in sorted(results):
        if status.get(tool) != "run":
            continue
        label, category = TOOL_LABELS.get(tool, (tool, "-"))
        summary = results[tool]["control"].latency_summary()
        if summary["mean_ms"] is None:
            # Spans both numeric columns: an unmeasured tool has no \pm to place,
            # and leaving the second cell empty would still typeset the separator.
            cell = f"\\multicolumn{{2}}{{c}}{{{NOT_ESTIMABLE}}}"
        else:
            cell = f"${summary['mean_ms']:.1f}$ & ${summary['sd_ms']:.1f}$"
        lines.append(f"{label} & {category} & {cell} \\\\")
    lines += ["\\bottomrule", "\\end{tabularx}", "\\end{table}", ""]
    return "\n".join(lines)


def emit_mcnemar_table(comparisons: dict[str, Any], reference: str) -> str:
    lines = [
        "% Generated by evaluation/analyze.py -- do not edit by hand.",
        "\\begin{table}[!t]",
        "\\caption{Exact McNemar comparisons against "
        f"{TOOL_LABELS.get(reference, (reference, ''))[0]}. "
        "$b$ counts cases the reference classifies correctly and the comparator "
        "does not, counting both missed violations and spurious findings; $c$ is "
        "the converse. $p$ is the two-sided exact binomial value, "
        "$p_{\\text{adj}}$ its Holm--Bonferroni correction across the tool family. "
        "The odds ratio carries a Haldane--Anscombe correction so that a zero "
        "discordant cell yields a finite estimate.}",
        "\\label{tab:mcnemar}",
        "\\centering",
        "\\small",
        "\\setlength{\\tabcolsep}{3pt}",
        # Numeric columns are right-aligned, not centred. Each is emitted with a
        # fixed number of decimal places below, so right alignment lines the
        # decimal points up; centring did not, and 0.45 next to 14.33 in the OR
        # column was the visible symptom.
        "\\begin{tabular}{@{}l r r r r r r@{}}",
        "\\toprule",
        # \textbf around a math group does not bold the symbol -- math ignores the
        # surrounding text font -- so the old \textbf{$b$} rendered unbold beside
        # bold text headers. Bolding a math variable properly needs \bm, which is
        # not loaded; plain italic math is the conventional alternative and is
        # what these cells already displayed, so nothing moves visually.
        "\\textbf{Comparator} & $b$ & $c$ & $p$ & "
        "$p_{\\text{adj}}$ & \\textbf{OR} & Cohen's $g$ \\\\",
        "\\midrule",
    ]
    if "error" in comparisons:
        lines.append(f"\\multicolumn{{7}}{{l}}{{{comparisons['error']}}} \\\\")
    for tool, entry in sorted(comparisons.items()):
        if tool == "error":
            continue
        label = TOOL_LABELS.get(tool, (tool, ""))[0]
        p_raw = entry["p_exact"]
        p_adj = entry.get("holm", {}).get("p_adjusted", p_raw)
        lines.append(
            f"{label} & {entry['b']} & {entry['c']} & "
            f"{_fmt_p(p_raw)} & {_fmt_p(p_adj)} & "
            f"{entry['odds_ratio']:.2f} & {entry['cohens_g']:.3f} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def emit_allpairs_table(rows: list[dict[str, Any]], level: MatchLevel) -> str:
    """Emits every pairwise comparison, with the correction applied across all of them."""
    lines = [
        "% Generated by evaluation/analyze.py -- do not edit by hand.",
        "% Regenerate with: python -m evaluation.analyze",
        f"% Matching strictness level: {level}",
        "\\begin{table}[!t]",
        "\\caption{Exact McNemar comparisons over every tool pair, with "
        "Holm--Bonferroni applied across the full set of pairs rather than across "
        "one tool's family. $b$ counts cases the left tool classifies correctly and "
        "the right does not; $c$ is the converse. Both error types count. The "
        "correction is stronger here than in Table~\\ref{tab:mcnemar} because the "
        "family is larger.}",
        "\\label{tab:allpairs}",
        "\\centering",
        "\\small",
        # Fixed columns with tight padding. As a plain tabular at the default
        # 6pt tabcolsep this ran 13.7pt past the column; at 3pt the twelve
        # inter-column gaps give back 36pt, which is ample. tabularx was tried
        # first and rejected: X columns are wider than the tool names need, so
        # every row came out badly underfull.
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}l l r r r r@{}}",
        "\\toprule",
        "\\textbf{Tool A} & \\textbf{Tool B} & $b$ & $c$ & $p$ & "
        "$p_{\\text{adj}}$ \\\\",
        "\\midrule",
    ]
    if not rows:
        lines.append("\\multicolumn{6}{l}{No tool pair produced comparable output.} \\\\")
    for row in rows:
        left = TOOL_LABELS.get(row["left"], (row["left"], ""))[0]
        right = TOOL_LABELS.get(row["right"], (row["right"], ""))[0]
        p_adj = row.get("holm", {}).get("p_adjusted", row["p_exact"])
        lines.append(
            f"{left} & {right} & {row['b']} & {row['c']} & "
            f"{_fmt_p(row['p_exact'])} & {_fmt_p(p_adj)} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def latex_defects(content: str) -> list[str]:
    """Reports structural defects in a generated LaTeX table.

    A stray brace in an emitter's caption string surfaces during typesetting as
    ``Extra }, or forgotten \\endgroup`` attributed to the generated file, which
    gives no indication of which emitter produced it. Catching it at generation
    time names the emitter instead. Escaped braces are discounted, since
    ``\\{`` is a literal character rather than a group delimiter.
    """
    defects: list[str] = []
    unescaped = re.sub(r"\\[{}]", "", content)
    delta = unescaped.count("{") - unescaped.count("}")
    if delta:
        direction = "unclosed {" if delta > 0 else "extra }"
        defects.append(f"brace imbalance ({direction} x{abs(delta)})")

    for index, line in enumerate(content.splitlines(), start=1):
        bare = re.sub(r"\\[{}]", "", line)
        if line.lstrip().startswith("\\caption") and bare.count("{") != bare.count("}"):
            defects.append(f"line {index}: caption braces do not balance on one line")

    # tabularx is counted separately rather than folded into the tabular check:
    # "\\begin{tabular}" is not a substring of "\\begin{tabularx}{...}", so an
    # emitter that opened tabularx and closed tabular would balance both counts at
    # zero and report clean. The layer-attribution table uses tabularx to let a
    # long configuration label wrap, so this is a live case, not a hypothetical.
    for environment in ("table", "tabular", "tabularx"):
        opens = content.count(f"\\begin{{{environment}}}")
        closes = content.count(f"\\end{{{environment}}}")
        if opens != closes:
            defects.append(f"{environment}: {opens} begin vs {closes} end")

    if "\\caption" in content and "\\label" not in content:
        defects.append("caption without label; \\ref to this table would print '??'")

    return defects
