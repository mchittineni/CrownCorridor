"""Tests for the generated-LaTeX structural guard.

Motivated by a real defect: a stray closing brace in the latency emitter's
caption produced ``results/tables/latency.tex:16: Extra }, or forgotten
\\endgroup``. The reported line was the end of the table, nine lines after the
actual mistake, and the reported file was a generated artefact -- so the error
named neither the cause nor the emitter responsible. Worse, it only surfaced when
someone happened to typeset the manuscript, which is the last point at which one
wants to discover that the analysis output is unusable.

The guard therefore runs at generation time and refuses to write a defective
table at all.
"""

from __future__ import annotations

import pytest

from evaluation.tables import _criterion_gain, latex_defects

WELL_FORMED = r"""% Generated by evaluation/analyze.py -- do not edit by hand.
\begin{table}[!t]
\caption{Measured per-case execution latency over 3 repetitions.}
\label{tab:latency}
\centering
\begin{tabular}{l r}
\toprule
\textbf{Tool} & \textbf{Latency (ms)} \\
\midrule
Checkov & $2623.6 \pm 43.2$ \\
\bottomrule
\end{tabular}
\end{table}
"""


def test_well_formed_table_has_no_defects():
    assert latex_defects(WELL_FORMED) == []


def test_detects_the_actual_regression():
    """The exact defect that shipped: one extra brace closing the caption."""
    broken = WELL_FORMED.replace(
        r"\caption{Measured per-case execution latency over 3 repetitions.}",
        r"\caption{Measured per-case execution latency over 3 repetitions.}}",
    )
    defects = latex_defects(broken)
    assert any("brace imbalance" in d for d in defects)
    assert any("extra }" in d for d in defects)
    # The caption check must name the offending line, since that is the
    # information the LaTeX error failed to provide.
    assert any("caption braces do not balance" in d for d in defects)


def test_detects_unclosed_brace():
    broken = WELL_FORMED.replace(r"\caption{Measured", r"\caption{{Measured")
    assert any("unclosed {" in d for d in latex_defects(broken))


def test_escaped_braces_are_not_counted_as_delimiters():
    """``\\{`` is a literal character; counting it would cause false alarms.

    Captions legitimately contain escaped braces when quoting LaTeX or JSON, and
    a guard that rejected them would push authors toward disabling it.
    """
    literal = WELL_FORMED.replace(
        r"\caption{Measured per-case execution latency over 3 repetitions.}",
        r"\caption{Latency, written as \texttt{\{"
        r"\"mean\": 1.0\}} in the manifest.}",
    )
    assert not any("brace imbalance" in d for d in latex_defects(literal))


def test_detects_unterminated_environment():
    truncated = WELL_FORMED.replace("\\end{tabular}\n", "")
    defects = latex_defects(truncated)
    assert any(d.startswith("tabular:") for d in defects)


def test_detects_tabularx_closed_as_tabular():
    """A tabularx opened and closed as tabular must not report clean.

    ``\\begin{tabular}`` is not a substring of ``\\begin{tabularx}{...}``, so
    counting only ``tabular`` leaves both counts at zero for this mismatch and the
    guard passes a file that will not typeset. The layer-attribution table uses
    tabularx, so the mismatch is reachable from a one-character edit to a live
    emitter.
    """
    mismatched = WELL_FORMED.replace(
        r"\begin{tabular}{l r}", r"\begin{tabularx}{\columnwidth}{@{}X r@{}}"
    )
    defects = latex_defects(mismatched)
    assert any(d.startswith("tabularx:") for d in defects), defects


def test_accepts_a_balanced_tabularx():
    """The new environment must not be reported as a defect when it is balanced."""
    balanced = WELL_FORMED.replace(
        r"\begin{tabular}{l r}", r"\begin{tabularx}{\columnwidth}{@{}X r@{}}"
    ).replace(r"\end{tabular}", r"\end{tabularx}")
    assert latex_defects(balanced) == []


def test_detects_caption_without_label():
    """A caption with no label makes every \\ref to the table print '??'.

    That failure is silent in the sense that the build still succeeds, so it can
    reach a submitted PDF. It is worth failing generation over.
    """
    unlabelled = WELL_FORMED.replace("\\label{tab:latency}\n", "")
    assert any("caption without label" in d for d in latex_defects(unlabelled))


def test_every_shipped_emitter_produces_clean_output():
    """Guards the emitters themselves, not just the guard.

    Runs over whatever tables are currently generated. Skips silently when none
    exist, because the harness legitimately refuses to emit tables for an empty
    corpus and this test must not force a fabricated one into being.
    """
    from evaluation.analyze import TABLE_DIR

    tables = sorted(TABLE_DIR.glob("*.tex")) if TABLE_DIR.is_dir() else []
    for table in tables:
        defects = latex_defects(table.read_text(encoding="utf-8"))
        assert defects == [], f"{table.name}: {defects}"


# --------------------------------------------------------------------------- #
# Criterion-gain nesting guard
# --------------------------------------------------------------------------- #
#
# The strictness table's Delta column is the paper's headline quantity. It is
# counted case by case rather than differenced from two true-positive totals,
# precisely so that a violation of the criteria's nesting cannot cancel against a
# gain elsewhere and leave a plausible number in the table. These tests pin that
# behaviour, because the subtraction is the obvious "simplification" a later
# reader would apply.


class _StubResult:
    """The two attributes ``_criterion_gain`` reads, and nothing else."""

    def __init__(self, tool: str, outcomes: dict[str, str]) -> None:
        self.tool = tool
        self.outcomes = outcomes


def test_criterion_gain_counts_cases_the_permissive_criterion_adds():
    control = _StubResult("stub", {"a": "TP", "b": "FN", "c": "FN", "d": "TN"})
    permissive = _StubResult("stub", {"a": "TP", "b": "TP", "c": "FN", "d": "TN"})
    assert _criterion_gain(control, permissive) == 1


def test_criterion_gain_rejects_a_case_lost_under_the_permissive_criterion():
    """Nesting forbids it: anything credited at `control` is credited at `any`."""
    control = _StubResult("stub", {"a": "TP", "b": "FN"})
    permissive = _StubResult("stub", {"a": "FN", "b": "TP"})
    with pytest.raises(ValueError, match="nesting of the criteria forbids"):
        _criterion_gain(control, permissive)


def test_criterion_gain_names_the_offending_case():
    control = _StubResult("stub", {"regressed": "TP"})
    permissive = _StubResult("stub", {"regressed": "FN"})
    with pytest.raises(ValueError, match="regressed"):
        _criterion_gain(control, permissive)
